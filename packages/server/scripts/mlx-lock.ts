// Writes src/sidecars/engines/mlx-requirements.txt: mlx-lm pinned with hashes of every dependency, for
// macOS 14+ on Apple Silicon and Python 3.12. Needs `uv` on PATH. Usage: bun scripts/mlx-lock.ts
import { join } from "node:path";
import { MLX_LM_VERSION } from "../src/sidecars/engines/mlx.ts";

const out = join(import.meta.dir, "../src/sidecars/engines/mlx-requirements.txt");
const compiled = Bun.spawnSync(
  [
    "uv",
    "pip",
    "compile",
    "-",
    "--generate-hashes",
    "--no-header",
    "--python-version",
    "3.12",
    "--python-platform",
    "aarch64-apple-darwin",
  ],
  {
    stdin: new TextEncoder().encode(`mlx-lm==${MLX_LM_VERSION}\n`),
    env: { ...process.env, MACOSX_DEPLOYMENT_TARGET: "14.0" },
  },
);
if (compiled.exitCode !== 0) throw new Error(compiled.stderr.toString());
await Bun.write(
  out,
  [
    "# mlx-lm and its dependencies for the built-in MLX engine (macOS 14+, Apple Silicon, Python 3.12).",
    "# Generated by packages/server/scripts/mlx-lock.ts — do not edit.",
    compiled.stdout.toString(),
  ].join("\n"),
);
console.log(`wrote ${out}`);
